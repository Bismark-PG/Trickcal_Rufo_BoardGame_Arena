/**
 * 직전 대사 연속 중복을 제외하고 다음 루포 반응을 선택한다. (엘프 닉네임 이스터에그 지원)
 * @param {string} nickname
 * @param {string|null} lastId
 * @param {boolean} elfTriggered
 */
export function pickNextRufoReaction(nickname, lastId = null, elfTriggered = false) {
    const hasElfNick = ONBOARDING_LIMITS.ELF_REGEX.test(String(nickname || ''));
    const pool = hasElfNick
        ? RUFO_CLICK_REACTIONS
        : RUFO_CLICK_REACTIONS.filter(r => !r.requiresElfNick);

    if (hasElfNick && !elfTriggered && lastId === null) {
        const elfReaction = pool.find(r => r.requiresElfNick);
        if (elfReaction) return elfReaction;
    }

    const candidates = pool.filter(r => r.id !== lastId);
    const source = candidates.length > 0 ? candidates : pool;
    return source[Math.floor(Math.random() * source.length)] || RUFO_CLICK_REACTIONS[0];
}
